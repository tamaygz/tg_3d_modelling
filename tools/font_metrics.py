#!/usr/bin/env python3
"""Generate lib/fonts_metrics.scad: advance widths and size factors of the bundled fonts.

    python3 tools/font_metrics.py

OpenSCAD 2021 has no textmetrics(), so text placed letter by letter (text on an arc, text fitted to a width) needs
the advance of every character. This reads them from the .ttf files in lib/fonts/ with Pillow and calibrates
OpenSCAD's size scale for each font by rendering test strings. Re-run it when a font is added to FONTS below.
Needs: Pillow, openscad.
"""
import re, subprocess, sys, tempfile
from pathlib import Path
from PIL import ImageFont

ROOT = Path(__file__).resolve().parent.parent
# font name as used in text(font=...) (see lib/fonts.scad font_for) -> file
FONTS = [
    ("Liberation Serif",              "LiberationSerif-Regular.ttf"),
    ("Liberation Serif:style=Bold",   "LiberationSerif-Bold.ttf"),
    ("Liberation Sans",               "LiberationSans-Regular.ttf"),
    ("Liberation Sans:style=Bold",    "LiberationSans-Bold.ttf"),
    ("Source Serif 4:style=Bold",     "SourceSerif4-Bold.ttf"),
    ("Lato:style=Bold",               "Lato-Bold.ttf"),
]
CHARS = "".join(chr(c) for c in range(32, 127))


def scad_extent(font_name, ttf, text, tmp):
    """x extent and y extent of text(text, size=100) rendered by OpenSCAD"""
    (tmp / "t.scad").write_text(f'use <{ttf}>\nlinear_extrude(1) text("{text}", size=100, font="{font_name}", halign="left", valign="baseline");\n')
    subprocess.run(["openscad", "-o", str(tmp / "t.stl"), str(tmp / "t.scad")], capture_output=True, check=True)
    xs, ys = [], []
    for m in re.finditer(r"vertex\s+(\S+)\s+(\S+)", (tmp / "t.stl").read_text()):
        xs.append(float(m.group(1))); ys.append(float(m.group(2)))
    return min(xs), max(xs), min(ys), max(ys)


def main():
    out = ["// GENERATED by tools/font_metrics.py: do not edit.",
           "// [font name, OpenSCAD units per em at size=1, cap height at size=1 (OpenSCAD units), characters, advances in em]",
           "FONT_METRICS = ["]
    with tempfile.TemporaryDirectory() as t:
        tmp = Path(t)
        for name, fn in FONTS:
            ttf = ROOT / "lib" / "fonts" / fn
            pil = ImageFont.truetype(str(ttf), 1000)
            adv = [round(pil.getlength(c) / 1000, 5) for c in CHARS]
            # OpenSCAD units per em: 20 H minus 10 H is exactly 10 advances of H
            h = adv[CHARS.index("H")]
            x10 = scad_extent(name, ttf, "H" * 10, tmp); x20 = scad_extent(name, ttf, "H" * 20, tmp)
            per_em = ((x20[1] - x20[0]) - (x10[1] - x10[0])) / (10 * h) / 100           # per unit of size
            cap = scad_extent(name, ttf, "H", tmp)[3] / 100
            esc = CHARS.replace("\\", "\\\\").replace('"', '\\"')
            out.append(f'  ["{name}", {per_em:.5f}, {cap:.5f}, "{esc}", {adv}],')
            print(f"{name:30s} em = {per_em:.4f} x size, cap height = {cap:.4f} x size")
    out[-1] = out[-1].rstrip(",")
    out.append("];")
    (ROOT / "lib" / "fonts_metrics.scad").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
