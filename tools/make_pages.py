#!/usr/bin/env python3
"""Prepare the web configurator site (yawkat/web-openscad-editor) for every project.

    python3 tools/make_pages.py --out build/pages-src [--repo-url URL] [--ref SHA] [--only name,name]

Writes a staging copy of the models and the library (same layout as the repo, so `../../lib/...` includes resolve)
plus an `editor.toml` for web-openscad-editor. The generator then bundles each model, every lib file it includes
and the bundled fonts into a static site: one self-contained configurator page per project.

What is prepared for each project (a folder under projects/ with <name>/<name>.scad, names starting with _ skipped):
  * `part = "all";` gets a dropdown of the project's parts, so single parts can be shown and exported;
  * coloured preview (parts are coloured by pick() from the `parts` table);
  * a description with links to the project's source, README and print files;
  * export file names like <name>-<part>.stl.
Also writes `projects.json` (name, title, page, source links) for the release notes.
Needs `openscad` on the PATH to read generated parts tables (falls back to a plain-text parse).
"""
import argparse, json, re, shutil, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import make_configurator

ROOT = Path(__file__).resolve().parent.parent
# pinned OpenSCAD snapshot used by the generator (AppImage for parameter extraction, WASM for the pages)
OPENSCAD_VERSION = "2026.01.19"


def title_of(scad: Path) -> str:
    first = scad.read_text().splitlines()[0]
    return re.sub(r"^//\s*", "", first) if first.startswith("//") else scad.stem


def toml_str(s: str) -> str:
    return json.dumps(s)            # JSON string escaping is valid for TOML basic strings


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="build/pages-src")
    ap.add_argument("--repo-url", default="https://github.com/tamaygz/tg_3d_modelling")
    ap.add_argument("--ref", default="main", help="commit or branch the source links point to")
    ap.add_argument("--only", default="", help="comma-separated project names (default: all)")
    a = ap.parse_args()
    out = Path(a.out).resolve()
    if out.exists():
        shutil.rmtree(out)
    (out / "projects").mkdir(parents=True)
    shutil.copytree(ROOT / "lib", out / "lib", ignore=shutil.ignore_patterns("README.md", "*.txt", "examples"))

    only = [n for n in a.only.split(",") if n]
    names = sorted(p.name for p in (ROOT / "projects").iterdir()
                   if (p / f"{p.name}.scad").exists() and not p.name.startswith("_") and (not only or p.name in only))
    toml = ["# generated by tools/make_pages.py", "[project]",
            'name = "tg_3d_modelling configurators"', f"uri = {toml_str(a.repo_url)}", "",
            "[openscad]", f'version = "{OPENSCAD_VERSION}"', 'font-source = "system"', ""]
    info = []
    for name in names:
        src = ROOT / "projects" / name / f"{name}.scad"
        parts = make_configurator.eval_parts(src) or make_configurator.parse_parts(src.read_text())
        ids = [p["id"] for p in parts if p["id"] != "all"]
        text, n = re.subn(r'^part\s*=\s*"all";.*$', 'part = "all"; // [' + ", ".join(["all"] + ids) + "]", src.read_text(), count=1, flags=re.M)
        if n != 1:
            sys.exit(f"{name}: no `part = \"all\";` line")
        bad = [l for l in text.splitlines() if re.match(r"\s*(include|use)\s*<[^>]+>\s*\S", l)]
        if bad:
            sys.exit(f"{name}: include/use lines must not have trailing text (the web export skips them): {bad[0]}")
        dst = out / "projects" / name
        dst.mkdir()
        (dst / f"{name}.scad").write_text(text)
        tree = f"{a.repo_url}/tree/{a.ref}/projects/{name}"
        title = title_of(src)
        desc = (f"<p>{title}</p><p>Pick a <b>part</b> to show and export a single printable piece; "
                f"<i>all</i> shows the assembly.</p>"
                f'<p><a href="{tree}">Source and README</a> · <a href="{tree}/{name}_print">print files</a> · '
                f'<a href="{a.repo_url}/tree/{a.ref}/lib">shared library</a></p>')
        toml += ["[[model]]", f'file = "projects/{name}/{name}.scad"', 'preview-style = "colors"',
                 f"description-extra-html = {toml_str(desc)}",
                 "export-file-stem = {js = " + toml_str(f"'{name}-' + part") + "}", "",
                 "[model.param-metadata.part]",
                 'description-html = "Which part to show and export (all = the whole assembly)"', ""]
        info.append({"name": name, "title": title, "page": name, "source": tree, "parts": ids})
        print(f"{name}: {len(ids)} parts")
    (out / "editor.toml").write_text("\n".join(toml))
    (out / "projects.json").write_text(json.dumps(info, indent=1))
    print(f"staged {len(names)} projects in {out}")


if __name__ == "__main__":
    main()
