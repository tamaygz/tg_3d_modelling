import _env
import json, math, sys, numpy as np
X0 = 913.68
font_file, font_name, letters_json = sys.argv[1], sys.argv[2], sys.argv[3]
lf = json.load(open('leaves_fit.json'))
Cm = np.array([X0, 959.])
leaves = []
for v in lf:
    bx, by, ang, L, W = v[:5]
    d = np.array([bx, by]) - Cm; r = float(np.hypot(*d)); a = math.degrees(math.atan2(d[1], d[0])) % 360
    lean = (ang - (a - 90) + 540) % 360 - 180
    leaves.append([round(a, 2), round(r, 1), round(lean, 2), round(L, 1), round(W, 1)])
leaves += json.load(open('low_leaves.json'))      # two bottom leaves, partly behind the banner
leaves.sort(key=lambda r: -r[0])
v = json.load(open('banner_joint.json'))
sizes = [7, 20, 16, 8, 7, 8, 10, 1]; P = []; i = 0
for k in sizes: P.append(v[i:i+k]); i += k
band, tail, fold, strip, loops, legs, ear, stroke = P
cx = lambda lst: [round(x - X0, 2) if j % 2 == 0 else round(x, 2) for j, x in enumerate(lst)]
# reorder tail: python order A,c1,T1,N,T2,c2,B,c3,c4,c5 matches banner_tail_pts
spec = [[round(x, 2) for x in band], cx(tail), cx(fold), cx(strip), [round(x, 3) for x in loops], [round(x, 2) for x in legs], cx(ear), round(stroke[0], 2)]
L = json.load(open(letters_json))
TA = json.load(open('textlayout_fit.json'))
BALL = json.load(open('ball_fit.json')); C = np.array(BALL['ring'][:2]); d = 2*BALL['ring'][2]; R = d/2
dc = BALL['disc']; cr = BALL['crescent']
BALLP = [round(d,2), round(BALL['ring'][3],2), round(dc[2]/R,4), [round((dc[0]-C[0])/d,5), round((dc[1]-C[1])/d,5)],
         [round((cr[0]-C[0])/d,5), round((cr[1]-C[1])/d,5)], round(cr[2]/R,4), round(cr[3],2), round(cr[4],2), round(cr[5],2), round(cr[6]/R,4)]
N = json.load(open('numeral_fit.json')); NUM = [[N[0][0], N[0][1], round(N[0][2]-C[0],3)], [N[1][0], N[1][1], round(N[1][2]-C[1],3)]]
out = ["// Bola Vuit logo REBUILT from the generic emblem elements (lib/emblem.scad), fitted to the original artwork.",
       "// Generated by the fitting scripts; px units of the original 1809 x 1716 frame, y up.",
       f"use <../fonts/{font_file}>", "use <../fonts/Lato-Bold.ttf>",
       f'BVR_FONT = "{font_name}";                 // closest open-licence match to the logo lettering',
       f"BVR_CENTER_X = {X0};",
       f"BVR_WREATH_C = [{X0}, 959];",
       "BVR_LEAVES = [   // left branch: [angle of base, radius, lean (+ out), length, width]"] + \
      [f"  {l}," for l in leaves] + ["];",
       f"BVR_BANNER = {json.dumps(spec)};   // ribbon_banner_2d spec, centre line at BVR_CENTER_X",
       "BVR_BALL_C = %s;   // ball centre" % json.dumps([round(x,2) for x in BALL['ring'][:2]]),
       "BVR_BALL = %s;     // pool_ball_2d: [d, ring_w, disc, disc_offset, hl_center, hl_r, hl_from, hl_to, hl_mid, hl_w]" % json.dumps(BALLP),
       'BVR_NUMERAL_FONT = "Lato:style=Bold";      // closest open match to the logo\'s "8"',
       "BVR_NUMERAL = %s;  // 2x3 matrix for text(\"8\", size=100), relative to the ball centre" % json.dumps(NUM),
       "BVR_TEXT_ARC = %s;  // arc_text_2d layout for any text: [centre x, centre y, radius, size, width, tracking, lean left, lean right, angle]" % json.dumps([round(TA[k], 3) for k in ("cx", "cy", "r", "size", "width", "tracking", "lean0", "lean1", "at")]),
       "BVR_LETTERS = [  // [text, 2x3 matrix applied to text(size=100, halign=left, valign=baseline)]"] + \
      [f'  ["{s}", {m}],' for s, m in L.items()] + ["];"]
open(_env.REPO / 'lib' / 'emblems' / 'bolavuit_rebuilt.scad', 'w').write("\n".join(out) + "\n")
print("\n".join(out))
